"""YSF host tests: the modem and channel simulation (ASan/UBSan). No radio.
Mirror of tools/test_nxdn.py for the YSF prototype (docs/ysf-c4fm.md).

    python3 tools/test_ysf.py

An optional cross-check against MMDVMHost's own classes runs when
research/protocol/MMDVMHost is present (tools/build_validators.sh): it decodes
frames our encoder built with MMDVM's CYSFFICH/CYSFPayload, and vice versa.
Without that checkout the step is skipped. No public YSF test vectors exist;
the vectors here are generated by our own encoder."""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/ysf-host"
MMDVM = ROOT / "research/protocol/MMDVMHost"
SAN = ["-fsanitize=address,undefined", "-fno-omit-frame-pointer"]
CFLAGS = ["-std=c11", "-O1", "-g", "-Wall", "-Wextra", "-Werror", *SAN, "-Isrc/ysf"]
LIB = [ROOT / "src/ysf/ysf_modem.c", ROOT / "src/ysf/ysf_frame.c", ROOT / "src/ysf/ysf_tx.c"]


def run(args, **kw):
    subprocess.run([str(a) for a in args], check=True, cwd=ROOT, **kw)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    run(["python3", "tools/gen_ysf_tables.py"])
    run(["clang", *CFLAGS, "tests/ysf/test_ysf_modem.c", "tests/ysf/ysf_channel.c", *LIB, "-lm",
         "-o", OUT / "test_ysf_modem"])
    run([OUT / "test_ysf_modem"])
    run(["clang", *CFLAGS, "tests/ysf/test_ysf_tx.c", "tests/ysf/ysf_channel.c", *LIB, "-lm",
         "-o", OUT / "test_ysf_tx"])
    run([OUT / "test_ysf_tx"])
    if not (MMDVM / "YSFFICH.cpp").exists():
        print("SKIP MMDVMHost oracle: research/protocol/MMDVMHost missing (tools/build_validators.sh)")
        return 0
    objs = []
    (OUT / "mmdvm").mkdir(exist_ok=True)
    for name in ("YSFFICH", "YSFPayload", "YSFConvolution", "Golay24128", "CRC", "AMBEFEC", "Hamming"):
        obj = OUT / "mmdvm" / (name + ".o")
        run(["clang++", "-std=c++17", "-O1", "-g", "-w", "-I" + str(MMDVM), "-c", MMDVM / (name + ".cpp"), "-o", obj])
        objs.append(obj)
    obj = OUT / "mmdvm" / "stubs.o"
    run(["clang++", "-std=c++17", "-O1", "-g", "-w", "-I" + str(MMDVM), "-c", "tests/ysf/stubs/mmdvm_stubs.cc",
         "-o", obj])
    objs.append(obj)
    cobjs = []
    for src in LIB:
        o = OUT / (Path(src).stem + ".o")
        run(["clang", "-std=c11", "-O1", "-g", *SAN, "-Isrc/ysf", "-c", src, "-o", o])
        cobjs.append(o)
    run(["clang++", "-std=c++17", "-O1", "-g", "-Wall", *SAN, "-I" + str(MMDVM), "-Isrc/ysf",
         "tests/ysf/test_ysf_mmdvm.cc", *objs, *cobjs, "-o", OUT / "test_ysf_mmdvm"])
    run([OUT / "test_ysf_mmdvm"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
